/// Cost of `tokens` at `price` in nano-USD, rounded half up. `None` when the
/// arithmetic overflows or a reported unit is unpriced on a non-free model
/// (reported as unknown cost, never as a wrong number).
pub fn cost_nano_usd(price: &Price, tokens: Tokens) -> Option<u64> {
    let token_unpriced = price.input_nano_usd_per_mtok == 0 && price.output_nano_usd_per_mtok == 0;
    let audio_unpriced = price.nano_usd_per_audio_second == 0;
    let free = token_unpriced && audio_unpriced;
    if !free
        && (((tokens.prompt != 0 || tokens.completion != 0) && token_unpriced)
            || (tokens.audio_ms != 0 && audio_unpriced))
    {
        return None;
    }
    let input = u128::from(tokens.prompt).checked_mul(price.input_nano_usd_per_mtok.into())?;
    let output =
        u128::from(tokens.completion).checked_mul(price.output_nano_usd_per_mtok.into())?;
    let audio = u128::from(tokens.audio_ms)
        .checked_mul(price.nano_usd_per_audio_second.into())?
        .checked_mul(1000)?;
    let total = input
        .checked_add(output)?
        .checked_add(audio)?
        .checked_add(500_000)?
        / 1_000_000;
    u64::try_from(total).ok()
}

/// Everything needed to account one request once it ends. Holds only `Arc`
/// clones; nothing is allocated until `finalize`.
pub struct UsageCapture {
    pub runtime: Arc<Runtime>,
    pub caller: Caller,
    pub request: RequestCtx,
    /// Metric label (the called name or `unknown`) and the caller's team.
    pub handles: Arc<RequestMetrics>,
    /// The name the client called, even when it is `unknown` to the metrics.
    pub requested: Arc<str>,
    /// The alias called, if any.
    pub alias: Option<Arc<str>>,
    /// The router behind the called name, if any.
    pub router: Option<Arc<str>>,
    /// The model (with the price) this request was served with.
    pub model: Option<Arc<Model>>,
    /// `model` is a fallback of the router.
    pub fallback: bool,
    /// Upstream attempts so far.
    pub attempts: u32,
    pub config_version: u64,
    /// Index into `API_ENDPOINTS`.
    pub endpoint: usize,
    pub stream: bool,
    pub status: u16,
}

impl UsageCapture {
    /// Records tokens/spend metrics and the tpm charge (only for REPORTED
    /// usage) and emits the event. Consumes the capture: exactly once.
    pub fn finalize(self, outcome: RequestOutcome, state: UsageState, tokens: Option<Tokens>) {
        let tokens = tokens.filter(|_| state == UsageState::Reported);
        let cost = tokens.and_then(|tokens| {
            let price = self.model.as_ref()?.price.as_ref()?;
            cost_nano_usd(price, tokens)
        });
        let metrics = &self.runtime.metrics;
        if outcome != RequestOutcome::Rejected {
            metrics.usage_captured(state);
        }
        let team = match &self.caller {
            Caller::Key(key) => &*key.team_id,
            Caller::Anonymous => "",
        };
        if let Some(tokens) = tokens {
            self.handles.record_tokens(tokens.prompt, tokens.completion);
            self.runtime.limiters.charge_tokens(
                &self.caller,
                tokens.prompt.saturating_add(tokens.completion),
            );
            if let Some(nano_usd) = cost.filter(|&nano_usd| nano_usd > 0) {
                metrics.spend(team, nano_usd);
            }
        }
        if !self.runtime.usage.enabled() {
            return;
        }
        let elapsed = self.request.started.elapsed();
        let key_id = match &self.caller {
            Caller::Key(key) => key.key_id.to_string(),
            Caller::Anonymous => String::new(),
        };
        let tokens = tokens.unwrap_or_default();
        self.runtime.usage.try_record(UsageEvent {
            request_id: self.request.request_id.to_string(),
            timestamp_unix_ms: self
                .request
                .started_at_unix_ms
                .saturating_add(i64::try_from(elapsed.as_millis()).unwrap_or(i64::MAX)),
            key_id,
            team_id: team.into(),
            requested: self.requested.to_string(),
            alias: self.alias.as_deref().unwrap_or_default().into(),
            router: self.router.as_deref().unwrap_or_default().into(),
            model: self
                .model
                .as_ref()
                .map(|d| d.name.clone())
                .unwrap_or_default(),
            upstream: self
                .model
                .as_ref()
                .map(|d| d.upstream.to_string())
                .unwrap_or_default(),
            upstream_model: self
                .model
                .as_ref()
                .map(|d| d.upstream_model.to_string())
                .unwrap_or_default(),
            fallback: self.fallback,
            attempts: self.attempts,
            endpoint: API_ENDPOINTS[self.endpoint].into(),
            status: self.status.into(),
            stream: self.stream,
            prompt_tokens: tokens.prompt,
            completion_tokens: tokens.completion,
            audio_ms: tokens.audio_ms,
            duration_ms: u32::try_from(elapsed.as_millis()).unwrap_or(u32::MAX),
            config_version: self.config_version,
            usage_state: state as i32,
            outcome: outcome as i32,
            started_at_unix_ms: self.request.started_at_unix_ms,
            cost_nano_usd: cost.unwrap_or(0),
            cost_known: cost.is_some(),
            kind: lumewarp_proto::usage::v1::TrafficKind::Llm as i32,
            ..Default::default()
        });
    }
}

/// Owns a capture while the request waits for upstream headers. If the
/// request future is dropped there (client gone, server shutdown abort), the
/// capture finalizes as CLIENT_CANCELLED / MISSING; every other path `take`s
/// it, so each request is accounted exactly once.
pub struct PendingCapture(Option<UsageCapture>);

impl PendingCapture {
    /// `capture.status` should be the cancellation status (499).
    pub fn new(capture: UsageCapture) -> Self {
        Self(Some(capture))
    }

    /// Upstream attempts so far, for a request cancelled during the next one.
    pub fn attempts(&mut self, attempts: u32) {
        if let Some(capture) = &mut self.0 {
            capture.attempts = attempts;
        }
    }

    /// Hands the capture to whoever finalizes it next.
    pub fn take(mut self) -> UsageCapture {
        self.0.take().expect("capture taken once")
    }

    /// Drops the capture without accounting: for requests that turn out to
    /// be invalid before any upstream attempt (no usage event, no metric).
    pub fn discard(mut self) {
        self.0.take();
    }
}

impl Drop for PendingCapture {
    fn drop(&mut self) {
        if let Some(capture) = self.0.take() {
            capture.finalize(RequestOutcome::ClientCancelled, UsageState::Missing, None);
        }
    }
}

