        // the handoff status and the final outcome.
        let mut recorder = TrafficRecorder::new(&runtime, &event(&request, &caller, 200, "echo"));
        recorder.finish(RequestOutcome::Completed);
        let recorded = rx.try_recv().expect("one event");
