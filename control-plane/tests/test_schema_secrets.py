# A column whose name promises a credential must not be classified as free text.
_SENSITIVE_NAME = re.compile(r"secret|password|nonce|verifier|token|credential", re.I)
_PLAIN_TEXT_CLASSES = {
    ColumnClass.PUBLIC,
    ColumnClass.PERSONAL,
    ColumnClass.CONFIG,
    ColumnClass.PROTOCOL,
}


def scanned_columns() -> set[tuple[str, str]]:
    columns = set()
    for table in Base.metadata.sorted_tables:
        for column in table.columns:
            if isinstance(column.type, Enum):
                continue
            if isinstance(column.type, Text | String | JSONB):
                columns.add((table.name, column.name))
    return columns


def test_every_text_string_or_jsonb_column_is_classified() -> None:
    missing = scanned_columns() - set(CLASSIFIED)
    assert not missing, f"classify these columns (or store a hash): {sorted(missing)}"


def test_classification_has_no_stale_entries() -> None:
    stale = set(CLASSIFIED) - scanned_columns()
    assert not stale, f"remove classifications for dropped columns: {sorted(stale)}"


def test_sensitive_looking_columns_are_not_plain_text() -> None:
    wrong = [
        (table, column, kind)
        for (table, column), kind in CLASSIFIED.items()
        if _SENSITIVE_NAME.search(column) and kind in _PLAIN_TEXT_CLASSES
    ]
    assert not wrong, f"store a hash, an env reference or an error class instead: {wrong}"


def test_known_secret_columns_use_a_safe_class() -> None:
    assert CLASSIFIED[("upstreams", "api_key_ref")] is ColumnClass.ENV_REF
    assert CLASSIFIED[("config_outbox", "last_error")] is ColumnClass.ERROR_CLASS
    assert CLASSIFIED[("audit_log", "details")] is ColumnClass.AUDIT_DETAILS


def test_login_state_table_stores_no_nonce_or_verifier() -> None:
    assert ("oidc_login_states", "nonce") not in scanned_columns()
    assert ("oidc_login_states", "code_verifier") not in scanned_columns()


async def test_migrated_table_has_no_login_state_secrets(engine) -> None:
    """The migration, not only the model, removed the columns."""
    async with engine.connect() as connection:
        rows = await connection.execute(
            text(
                "SELECT column_name FROM information_schema.columns"
                " WHERE table_name = 'oidc_login_states'"
            )
        )
        names = {row[0] for row in rows}
    assert names == {"id", "state_hash", "return_path", "redirect_uri", "expires_at"}
