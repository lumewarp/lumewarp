"""Every Text/String/JSONB column is classified as non-secret (or refused).

A new column that is not in `CLASSIFIED` fails the scan, so plaintext credentials cannot be
introduced by accident; the reviewer then has to pick a class. HASH columns are LargeBinary
digests and not scanned here.
"""

