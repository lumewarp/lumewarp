#!/usr/bin/env bash
# Regenerate the Python protobuf/gRPC modules for the control plane from proto/.
# Output is checked in under control-plane/src/lumewarp_control_plane/_proto/.
# Idempotent: running it twice yields no diff. The generator version is pinned
# by grpcio-tools in control-plane/uv.lock.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
proto_dir="$root/proto"
out="$root/control-plane/src/lumewarp_control_plane/_proto"
pkg="lumewarp_control_plane._proto"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

mapfile -t protos < <(cd "$proto_dir" && find lumewarp -name '*.proto' | LC_ALL=C sort)

(cd "$root/control-plane" && uv run --frozen python -m grpc_tools.protoc \
  -I "$proto_dir" \
  --python_out="$tmp" \
  --pyi_out="$tmp" \
  --grpc_python_out="$tmp" \
  "${protos[@]}")

# protoc emits absolute imports rooted at the proto package ("from lumewarp.config.v1
# import ..."); rewrite them so the modules load from the installed wheel.
find "$tmp" -name '*.py' -o -name '*.pyi' | while read -r f; do
  sed -i -E "s/^from lumewarp\.([a-z0-9_.]+) import /from ${pkg}.lumewarp.\1 import /" "$f"
done

# Every directory is a regular package.
find "$tmp" -type d | while read -r d; do
  : >"$d/__init__.py"
done
printf '"""Generated by scripts/gen-proto.sh from proto/. Do not edit."""\n' >"$tmp/__init__.py"

rm -rf "$out"
mkdir -p "$out"
cp -R "$tmp/." "$out/"
